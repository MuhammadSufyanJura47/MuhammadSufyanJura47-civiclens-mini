"""
Build a copyable plain-text report for a complaint.

The report deliberately includes disclaimers: the AI priority is a SUGGESTION
requiring human review, and the complaint is NOT officially verified.
"""

from __future__ import annotations

from typing import Any


def build_report(record: dict[str, Any], *, dup_method: str = "lexical") -> str:
    a = record.get("analysis") or {}
    loc = a.get("location") or "Not provided by citizen"
    dur = a.get("reported_duration") or "Not provided by citizen"
    evidence = a.get("evidence_mentioned") or []
    evidence_str = "; ".join(evidence) if evidence else "None mentioned by citizen"
    reasons = a.get("priority_reasons") or []
    reasons_str = "\n".join(f"    - {r}" for r in reasons) if reasons else "    - (none given)"

    dups = record.get("duplicates") or []
    if dups:
        dup_lines = "\n".join(
            f"    - #{d.get('id')} (similarity {d.get('score')}): {d.get('summary','')}"
            for d in dups
        )
        dup_block = f"Possible duplicates ({dup_method} matching):\n{dup_lines}"
    else:
        dup_block = f"Possible duplicates ({dup_method} matching): none found"

    next_step = _next_step(a.get("suggested_priority", "Medium"), a.get("category", "Other"))

    return f"""CIVICLENS MINI — COMPLAINT REPORT
=====================================
Complaint ID : {record.get('id')}
Logged (UTC) : {record.get('created_at')}
Status       : {record.get('status')}
Sample data  : {"YES — demonstration only" if record.get('is_sample') else "No"}

ORIGINAL COMPLAINT
------------------
{record.get('text','').strip()}

AI ANALYSIS (open-weight model — NOT an official determination)
---------------------------------------------------------------
Category          : {a.get('category','Other')}
Summary           : {a.get('summary','')}
Reported duration : {dur}
Location          : {loc}
Evidence          : {evidence_str}

Suggested priority: {a.get('suggested_priority','Medium')}   [AI SUGGESTION — requires human review]
Reasons:
{reasons_str}

{dup_block}

RECOMMENDED NEXT STEP
---------------------
{next_step}

DISCLAIMER
----------
This complaint has NOT been officially verified. The category and priority above
are AI suggestions generated by an open-weight model and must be reviewed by a
human officer before any action is taken. No location or evidence was added by
the AI beyond what the citizen stated.
"""


def _next_step(priority: str, category: str) -> str:
    base = {
        "Critical": "Escalate immediately to the on-call municipal officer for the "
        f"'{category}' department and dispatch an inspection within 24 hours.",
        "High": f"Assign to the '{category}' department for inspection within 2–3 "
        "working days and acknowledge receipt to the citizen.",
        "Medium": f"Queue for the '{category}' department's standard work schedule "
        "and update the citizen with an expected timeline.",
        "Low": f"Log under the '{category}' backlog for batch handling and notify "
        "the citizen that it has been recorded.",
    }.get(priority, "Review and route to the appropriate department.")
    return base + " (Human officer to confirm before acting.)"
